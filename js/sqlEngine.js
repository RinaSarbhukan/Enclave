/**
 * Enclave - SQL Engine Module (AI Query)
 * Dataset loading, SELECT-only validator, identifier checks, and sandboxed execution.
 *
 * SECURITY CONTRACT:
 * - Only a single SELECT statement is permitted (FR-18).
 * - All referenced column identifiers must appear in the permitted schema (FR-19).
 * - Only allow-listed SQL functions may be called (FR-18).
 * - Execution never mutates the underlying dataset (FR-21).
 * - Result rows are capped and execution is time-bounded (FR-20).
 */

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

/** Maximum rows returned in query results (FR-20). */
export const MAX_RESULT_ROWS = 10_000;

/** Execution timeout in milliseconds (FR-20). */
export const EXECUTION_TIMEOUT_MS = 10_000;

/**
 * Allow-listed SQL function names. Any function NOT in this list causes rejection (FR-18).
 * Case-insensitive.
 */
const ALLOWED_FUNCTIONS = new Set([
  // Aggregates
  'count', 'sum', 'avg', 'min', 'max',
  // String
  'lower', 'upper', 'trim', 'ltrim', 'rtrim', 'length', 'len',
  'substr', 'substring', 'replace', 'concat', 'coalesce', 'ifnull', 'nullif',
  'left', 'right', 'charindex', 'instr',
  // Numeric
  'abs', 'round', 'floor', 'ceil', 'ceiling', 'mod', 'power', 'sqrt',
  // Date / time
  'year', 'month', 'day', 'strftime', 'date', 'datepart', 'datediff',
  'now', 'getdate', 'current_date',
  // Conversion
  'cast', 'convert',
  // Conditional
  'iif', 'iff', 'case',
  // Window / ranking (read-only)
  'row_number', 'rank', 'dense_rank', 'ntile',
]);

/**
 * Keywords that indicate DDL / DML / multi-statement attacks.
 * These must never appear as top-level statement keywords (FR-18).
 */
const FORBIDDEN_STATEMENT_KEYWORDS = [
  'INSERT', 'UPDATE', 'DELETE', 'DROP', 'CREATE', 'ALTER', 'TRUNCATE',
  'REPLACE', 'MERGE', 'EXEC', 'EXECUTE', 'CALL', 'GRANT', 'REVOKE',
  'BEGIN', 'COMMIT', 'ROLLBACK', 'ATTACH', 'DETACH', 'PRAGMA',
];

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------

/**
 * Validates a SQL string generated by the LLM against all security rules.
 * Returns { valid: true } or { valid: false, reason: string }.
 *
 * @param {string} sql - The raw SQL string to validate
 * @param {Array<{key:string,label:string}>} permittedHeaders - Columns available in the dataset
 * @param {Set<string>} [excludedColumnKeys=new Set()] - Excluded column keys (FR-8)
 * @returns {{ valid: boolean, reason?: string }}
 */
export function validateSql(sql, permittedHeaders, excludedColumnKeys = new Set()) {
  if (typeof sql !== 'string' || !sql.trim()) {
    return { valid: false, reason: 'No SQL was generated.' };
  }

  const trimmed = sql.trim();

  // 1. Must be a single statement — detect multiple statements (FR-18)
  if (_hasMultipleStatements(trimmed)) {
    return { valid: false, reason: 'Only a single SELECT statement is allowed.' };
  }

  // 2. Must start with SELECT (FR-18)
  const upperTrimmed = trimmed.toUpperCase().replace(/\s+/g, ' ');
  if (!upperTrimmed.startsWith('SELECT')) {
    return { valid: false, reason: 'Only SELECT statements are permitted.' };
  }

  // 3. Check for forbidden statement keywords (FR-18)
  for (const kw of FORBIDDEN_STATEMENT_KEYWORDS) {
    // Match keyword as a whole word (not inside column names or string literals)
    const kwRegex = new RegExp(`\\b${kw}\\b`, 'i');
    const sqlWithoutStrings = _removeStringLiterals(trimmed);
    if (kwRegex.test(sqlWithoutStrings)) {
      return { valid: false, reason: `SQL contains a forbidden keyword: ${kw}.` };
    }
  }

  // 4. Check for comments that might hide statements (FR-18)
  if (/\/\*[\s\S]*?\*\//.test(trimmed) || /--/.test(trimmed) || /;[\s\S]*\S/.test(trimmed)) {
    // Allow trailing semicolon but not comments or multiple statements after semicolon
    const withoutTrailingSemi = trimmed.replace(/;\s*$/, '');
    if (/\/\*[\s\S]*?\*\//.test(withoutTrailingSemi) || /--/.test(withoutTrailingSemi)) {
      return { valid: false, reason: 'SQL must not contain comments.' };
    }
  }

  // 5. Check for sub-queries that access system tables or arbitrary identifiers
  const sqlNormalized = _removeStringLiterals(trimmed).toUpperCase();

  // 6. Extract and validate function names (FR-18)
  const functionCallRegex = /\b([a-zA-Z_][a-zA-Z0-9_]*)\s*\(/g;
  let match;
  while ((match = functionCallRegex.exec(_removeStringLiterals(trimmed))) !== null) {
    const fnName = match[1].toLowerCase();
    // Skip SQL keywords that look like functions (CASE, etc.)
    if (['case', 'when', 'then', 'else', 'end'].includes(fnName)) continue;
    if (!ALLOWED_FUNCTIONS.has(fnName)) {
      return { valid: false, reason: `Function "${match[1]}" is not permitted.` };
    }
  }

  // 7. Verify column identifiers reference only permitted columns (FR-19)
  const permitted = new Set([
    ...permittedHeaders
      .filter(h => !excludedColumnKeys.has(h.key))
      .flatMap(h => [
        h.key.toLowerCase(),
        h.label.toLowerCase(),
        // Also allow normalized key with underscores
        h.label.toLowerCase().replace(/[^a-z0-9_]+/g, '_'),
        // Also allow quoted variants
        `"${h.key.toLowerCase()}"`,
        `"${h.label.toLowerCase()}"`,
        `[${h.key.toLowerCase()}]`,
        `[${h.label.toLowerCase()}]`,
      ]),
    // Allow the table name
    'data',
  ]);

  const identifierErrors = _findUnknownIdentifiers(trimmed, permitted, permittedHeaders, excludedColumnKeys);
  if (identifierErrors.length > 0) {
    return {
      valid: false,
      reason: `Unknown column(s): ${identifierErrors.slice(0, 3).join(', ')}. Only dataset columns may be referenced.`,
    };
  }

  return { valid: true };
}

/**
 * Checks whether a SQL string appears to contain multiple statements.
 * @param {string} sql
 * @returns {boolean}
 */
function _hasMultipleStatements(sql) {
  // Remove string literals first to avoid false positives from semicolons inside strings
  const cleaned = _removeStringLiterals(sql);
  // A trailing semicolon is fine; a semicolon followed by non-whitespace is not
  return /;[\s\S]*\S/.test(cleaned.replace(/;\s*$/, ''));
}

/**
 * Returns a copy of the SQL with string literals replaced by empty strings
 * to prevent false positives when scanning for keywords.
 * @param {string} sql
 * @returns {string}
 */
function _removeStringLiterals(sql) {
  // Remove single-quoted strings
  return sql.replace(/'(?:[^'\\]|\\.)*'/g, "''");
}

/**
 * Extracts declared aliases from the SQL string.
 * @param {string} sqlNoStrings
 * @param {Set<string>} [excludedColumnKeys]
 * @returns {Set<string>}
 */
function _extractDeclaredAliases(sqlNoStrings, excludedColumnKeys = new Set()) {
  const aliases = new Set();

  // 1. Explicit AS aliases: AS foo, AS "foo", AS [foo], AS `foo`
  const asRegex = /\bAS\s+([a-zA-Z_][a-zA-Z0-9_]*|"[^"]+"|`[^`]+`|\[[^\]]+\])/gi;
  let m;
  while ((m = asRegex.exec(sqlNoStrings)) !== null) {
    const raw = m[1].replace(/["`\[\]]/g, '').trim().toLowerCase();
    if (raw && !excludedColumnKeys.has(raw)) {
      aliases.add(raw);
    }
  }

  // 2. Table alias after FROM data: FROM data [AS] d
  const tableAliasRegex = /\bFROM\s+(?:data|\?)(?:\s+AS)?\s+([a-zA-Z_][a-zA-Z0-9_]*)/gi;
  while ((m = tableAliasRegex.exec(sqlNoStrings)) !== null) {
    const raw = m[1].replace(/["`\[\]]/g, '').trim().toLowerCase();
    if (!['where', 'group', 'order', 'having', 'limit', 'join', 'left', 'right', 'inner'].includes(raw)) {
      aliases.add(raw);
    }
  }

  // 3. Trailing aliases in SELECT clause before FROM: SELECT col my_alias, SUM(x) total FROM data
  const selectMatch = sqlNoStrings.match(/^\s*SELECT\s+([\s\S]*?)\s+FROM\b/i);
  if (selectMatch) {
    const selectBody = selectMatch[1];
    let depth = 0;
    let current = '';
    const parts = [];
    for (let i = 0; i < selectBody.length; i++) {
      const char = selectBody[i];
      if (char === '(') depth++;
      else if (char === ')') depth = Math.max(0, depth - 1);
      else if (char === ',' && depth === 0) {
        parts.push(current);
        current = '';
        continue;
      }
      current += char;
    }
    if (current) parts.push(current);

    for (const part of parts) {
      const match = part.trim().match(/(?:\)|[a-zA-Z0-9_\]"`])\s+([a-zA-Z_][a-zA-Z0-9_]*)$/i);
      if (match) {
        const potentialAlias = match[1].toLowerCase();
        if (!SQL_KEYWORDS.has(potentialAlias) && !ALLOWED_FUNCTIONS.has(potentialAlias) && !excludedColumnKeys.has(potentialAlias)) {
          aliases.add(potentialAlias);
        }
      }
    }
  }

  return aliases;
}

/** Standard SQL keywords, data types, and date parts */
const SQL_KEYWORDS = new Set([
  'select', 'from', 'where', 'and', 'or', 'not', 'in', 'is', 'null',
  'group', 'by', 'order', 'having', 'limit', 'offset', 'asc', 'desc',
  'as', 'on', 'join', 'left', 'right', 'inner', 'outer', 'cross', 'full',
  'union', 'all', 'distinct', 'case', 'when', 'then', 'else', 'end',
  'between', 'like', 'ilike', 'exists', 'any', 'some', 'true', 'false',
  'top', 'with', 'over', 'partition', 'rows', 'range', 'unbounded',
  'preceding', 'following', 'current', 'row', 'data', 'nulls', 'first', 'last',
  // Types used in CAST / CONVERT
  'int', 'integer', 'bigint', 'smallint', 'tinyint', 'float', 'double',
  'real', 'decimal', 'numeric', 'number', 'varchar', 'char', 'text',
  'string', 'date', 'time', 'datetime', 'timestamp', 'boolean', 'bool',
  // Date parts used in EXTRACT / DATEPART / DATEDIFF
  'year', 'quarter', 'month', 'week', 'day', 'dayofweek', 'hour', 'minute', 'second',
  'extract', 'interval', '__col__',
]);

/**
 * Extracts identifiers from the SQL and returns those that don't match
 * any permitted column key, label, or declared alias.
 * @param {string} sql
 * @param {Set<string>} permitted
 * @param {Array<{key:string,label:string}>} headers
 * @param {Set<string>} [excludedColumnKeys]
 * @returns {string[]}
 */
function _findUnknownIdentifiers(sql, permitted, headers, excludedColumnKeys = new Set()) {
  const unknown = [];
  const sqlNoStrings = _removeStringLiterals(sql);

  // 1. Extract all declared aliases (AS alias, table alias, SELECT list aliases)
  const declaredAliases = _extractDeclaredAliases(sqlNoStrings, excludedColumnKeys);
  for (const alias of declaredAliases) {
    permitted.add(alias);
    permitted.add(`[${alias}]`);
    permitted.add(`"${alias}"`);
  }

  // 2. Check and mask quoted/bracketed identifiers: [col name], "col name", `col name`
  const quotedRegex = /(?:\[([^\]]+)\]|"([^"]+)"|`([^`]+)`)/g;
  const sqlWithMaskedQuotes = sqlNoStrings.replace(quotedRegex, (fullMatch, g1, g2, g3) => {
    const ident = (g1 || g2 || g3 || '').trim().toLowerCase();
    if (ident && !permitted.has(ident) && !permitted.has(`[${ident}]`) && !permitted.has(`"${ident}"`)) {
      if (!unknown.includes(fullMatch)) {
        unknown.push(fullMatch);
      }
    }
    return ' __col__ ';
  });

  // 3. Extract bare identifiers
  const identRegex = /\b([a-zA-Z_][a-zA-Z0-9_]*)\b/g;
  let m;
  while ((m = identRegex.exec(sqlWithMaskedQuotes)) !== null) {
    const tok = m[1].toLowerCase();
    if (SQL_KEYWORDS.has(tok)) continue;
    if (ALLOWED_FUNCTIONS.has(tok)) continue;
    // Check if it's a number
    if (/^\d+$/.test(tok)) continue;
    // Check if it matches any permitted key/label/alias
    if (permitted.has(tok) || permitted.has(`"${tok}"`) || permitted.has(`[${tok}]`)) continue;
    // Check by stripping quotes or underscores
    const stripped = m[1].replace(/["\[\]]/g, '').toLowerCase();
    if (permitted.has(stripped)) continue;

    if (!unknown.includes(m[1])) {
      unknown.push(m[1]);
    }
  }

  return unknown;
}

