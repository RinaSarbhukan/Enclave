/**
 * Lazily loads AlaSQL from CDN.
 * AlaSQL is loaded globally via <script> in index.html.
 * Retries for up to 5 seconds in case the script is still loading.
 * @returns {Promise<any>} alasql function
 */
async function _getAlaSql() {
  // Check all known global attachment points
  const _check = () =>
    (typeof globalThis !== 'undefined' && globalThis.alasql) ||
    (typeof window !== 'undefined' && window.alasql) ||
    (typeof self !== 'undefined' && self.alasql) ||
    null;

  let alasql = _check();
  if (alasql) return alasql;

  // Retry up to 50 times × 100 ms = 5 seconds
  for (let i = 0; i < 50; i++) {
    await new Promise(r => setTimeout(r, 100));
    alasql = _check();
    if (alasql) return alasql;
  }

  throw new SqlEngineError('ENGINE_UNAVAILABLE', 'SQL engine (AlaSQL) failed to load. Please check your internet connection and refresh the page.');
}

/**
 * Converts rows (Array<Map>) to plain objects for AlaSQL.
 * @param {Array<Map<string,any>>} rows
 * @param {Array<{key:string}>} headers
 * @returns {Array<object>}
 */
function _mapsToObjects(rows, headers) {
  return rows.map(row => {
    const obj = {};
    for (const h of headers) {
      const val = row.get(h.key);
      // Convert Date to ISO string for SQL compatibility
      const formatted = val instanceof Date ? val.toISOString() : val;
      obj[h.key] = formatted;
      if (h.label && h.label !== h.key) {
        obj[h.label] = formatted;
        obj[h.label.toLowerCase()] = formatted;
      }
      if (h.label && /\s/.test(h.label)) {
        const underLabel = h.label.replace(/\s+/g, '_');
        obj[underLabel] = formatted;
        obj[underLabel.toLowerCase()] = formatted;
      }
    }
    return obj;
  });
}

/**
 * Executes a validated SELECT SQL query against the provided dataset.
 * Never mutates the original data.
 *
 * @param {string} sql - Validated SELECT SQL
 * @param {Array<{key:string,label:string,type:string}>} headers
 * @param {Array<Map<string,any>>} rows
 * @param {AbortSignal} [signal]
 * @returns {Promise<{rows: Array<object>, truncated: boolean}>}
 * @throws {SqlEngineError}
 */
export async function executeSql(sql, headers, rows, signal) {
  const alasql = await _getAlaSql();
  if (alasql && alasql.options) {
    alasql.options.casesensitive = false;
  }

  // Convert Map rows to plain objects
  const dataObjects = _mapsToObjects(rows, headers);

  // Normalize SQL — replace "FROM data" with the AlaSQL table var reference
  // AlaSQL can query arrays directly via: SELECT ... FROM ? WHERE ...
  // We pass the data array as a parameter

  // Replace table reference 'data' with '?'
  const sqlForExec = sql.trim().replace(/\bFROM\s+data\b/i, 'FROM ?').replace(/;\s*$/, '');

  return new Promise((resolve, reject) => {
    // Check abort before starting
    if (signal?.aborted) {
      return reject(new SqlEngineError('CANCELLED', 'Query was cancelled.'));
    }

    const timeoutHandle = setTimeout(() => {
      reject(new SqlEngineError('TIMEOUT', 'Query timed out (10 s). Try a simpler question.'));
    }, EXECUTION_TIMEOUT_MS);

    const abortHandler = () => {
      clearTimeout(timeoutHandle);
      reject(new SqlEngineError('CANCELLED', 'Query was cancelled.'));
    };
    if (signal) signal.addEventListener('abort', abortHandler, { once: true });

    try {
      let result;
      try {
        result = alasql(sqlForExec, [dataObjects]);
      } catch (err) {
        clearTimeout(timeoutHandle);
        if (signal) signal.removeEventListener('abort', abortHandler);
        return reject(new SqlEngineError('EXECUTION_ERROR', `SQL error: ${err.message || 'Unknown error'}`));
      }

      clearTimeout(timeoutHandle);
      if (signal) signal.removeEventListener('abort', abortHandler);

      if (!Array.isArray(result)) {
        // Scalar result (e.g. COUNT(*))
        result = [result];
      }

      const truncated = result.length > MAX_RESULT_ROWS;
      resolve({
        rows: result.slice(0, MAX_RESULT_ROWS),
        truncated,
      });
    } catch (err) {
      clearTimeout(timeoutHandle);
      if (signal) signal.removeEventListener('abort', abortHandler);
      reject(new SqlEngineError('EXECUTION_ERROR', `Unexpected error: ${err.message}`));
    }
  });
}

// ---------------------------------------------------------------------------
// Error class
// ---------------------------------------------------------------------------

export class SqlEngineError extends Error {
  /**
   * @param {'ENGINE_UNAVAILABLE'|'EXECUTION_ERROR'|'TIMEOUT'|'CANCELLED'} code
   * @param {string} message
   */
  constructor(code, message) {
    super(message);
    this.name = 'SqlEngineError';
    this.code = code;
  }
}

